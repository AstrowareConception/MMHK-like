-- V103 — explicitly qualified neutral-without-hero encounter resolution.
-- Research: data/Jactari/src/scripts/combat.min.js, defender status=PNJ,
-- no hero, no "attrition_pnj": attacker win => all starting neutral
-- units lost; defender win => no lasting neutral deaths.
-- This is NOT a mine activation, territorial capture, XP or loot policy.

-- Not even synthetic neutral encounters are assumed to be no-hero/non-attrition.
CREATE TABLE pve_lab_neutral_defender_profiles (
  encounter_id uuid PRIMARY KEY REFERENCES region_encounters(encounter_id)
    ON DELETE CASCADE,
  no_hero_confirmed boolean NOT NULL CHECK(no_hero_confirmed),
  no_attrition_confirmed boolean NOT NULL CHECK(no_attrition_confirmed),
  source_ref text NOT NULL CHECK(length(source_ref) BETWEEN 3 AND 255),
  qualified_at timestamptz NOT NULL DEFAULT clock_timestamp()
);

CREATE TABLE pve_lab_neutral_resolution_policies (
  world_id text PRIMARY KEY REFERENCES worlds(world_id) ON DELETE CASCADE,
  policy_id text NOT NULL DEFAULT 'LAB-NEUTRAL-NO-HERO-RESOLUTION-V1'
    CHECK(policy_id='LAB-NEUTRAL-NO-HERO-RESOLUTION-V1'),
  enabled boolean NOT NULL DEFAULT false,
  source_ref text NOT NULL CHECK(length(source_ref) BETWEEN 3 AND 255),
  configured_at timestamptz NOT NULL DEFAULT clock_timestamp()
);

CREATE FUNCTION enforce_pve_neutral_resolution_world_v103() RETURNS trigger
LANGUAGE plpgsql AS $neutralworld$
BEGIN
  IF NEW.enabled AND NOT EXISTS (
    SELECT 1 FROM pve_travel_policies t
      JOIN pve_lab_casualty_policies c ON c.world_id=t.world_id
      WHERE t.world_id=NEW.world_id
        AND t.policy_id LIKE 'LAB-%' AND NOT t.historically_certified
        AND c.enabled
  ) THEN
    RAISE EXCEPTION 'Neutral resolution requires enabled V102 casualties in a LAB world'
      USING ERRCODE='23514';
  END IF;
  RETURN NEW;
END;
$neutralworld$;
CREATE TRIGGER pve_neutral_world_guard_v103
BEFORE INSERT OR UPDATE ON pve_lab_neutral_resolution_policies
FOR EACH ROW EXECUTE FUNCTION enforce_pve_neutral_resolution_world_v103();

ALTER TABLE pve_missions ADD COLUMN neutral_resolution_snapshot jsonb;
ALTER TABLE pve_missions ADD CONSTRAINT pve_neutral_resolution_shape_v103
CHECK (neutral_resolution_snapshot IS NULL OR (
  jsonb_typeof(neutral_resolution_snapshot)='object'
  AND neutral_resolution_snapshot->>'policy_id'='LAB-NEUTRAL-NO-HERO-RESOLUTION-V1'
  AND jsonb_typeof(neutral_resolution_snapshot->'enabled')='boolean'
  AND jsonb_typeof(neutral_resolution_snapshot->'no_hero_verified')='boolean'
  AND jsonb_typeof(neutral_resolution_snapshot->'no_attrition_verified')='boolean'
  AND jsonb_typeof(neutral_resolution_snapshot->'source_ref') IN ('string','null')
  AND jsonb_typeof(neutral_resolution_snapshot->'profile_source_ref') IN ('string','null')
));

CREATE FUNCTION freeze_pve_neutral_resolution_v103() RETURNS trigger
LANGUAGE plpgsql AS $freeze$
DECLARE
  policy_enabled boolean;
  policy_source text;
  profile_source text;
BEGIN
  IF NEW.neutral_resolution_snapshot IS NOT NULL THEN
    RAISE EXCEPTION 'Neutral resolution snapshot must be generated by the server'
      USING ERRCODE='23514';
  END IF;
  SELECT p.enabled,p.source_ref INTO policy_enabled,policy_source
    FROM pve_lab_neutral_resolution_policies p
    JOIN cities c ON c.world_id=p.world_id
    WHERE c.city_id=NEW.city_id
    FOR SHARE OF p;
  SELECT n.source_ref INTO profile_source
    FROM pve_lab_neutral_defender_profiles n
    WHERE n.encounter_id=NEW.encounter_id
      AND n.no_hero_confirmed AND n.no_attrition_confirmed
    FOR SHARE;
  NEW.neutral_resolution_snapshot=jsonb_build_object(
    'policy_id','LAB-NEUTRAL-NO-HERO-RESOLUTION-V1',
    'enabled',COALESCE(policy_enabled,false),
    'source_ref',policy_source,
    'no_hero_verified',profile_source IS NOT NULL,
    'no_attrition_verified',profile_source IS NOT NULL,
    'profile_source_ref',profile_source
  );
  RETURN NEW;
END;
$freeze$;

CREATE TRIGGER pve_freeze_neutral_resolution_v103
BEFORE INSERT ON pve_missions FOR EACH ROW
EXECUTE FUNCTION freeze_pve_neutral_resolution_v103();

CREATE FUNCTION protect_pve_neutral_resolution_snapshot_v103() RETURNS trigger
LANGUAGE plpgsql AS $immut$
BEGIN
  IF OLD.neutral_resolution_snapshot IS DISTINCT FROM NEW.neutral_resolution_snapshot THEN
    RAISE EXCEPTION 'Frozen neutral resolution policy cannot change'
      USING ERRCODE='23514';
  END IF;
  RETURN NEW;
END;
$immut$;
CREATE TRIGGER pve_neutral_snapshot_immutable_v103
BEFORE UPDATE ON pve_missions FOR EACH ROW
EXECUTE FUNCTION protect_pve_neutral_resolution_snapshot_v103();

-- Only successful, qualified neutral encounter resolutions enter this ledger.
CREATE TABLE pve_lab_neutral_resolutions (
  mission_id uuid PRIMARY KEY REFERENCES pve_missions(mission_id) ON DELETE CASCADE,
  encounter_id uuid NOT NULL UNIQUE,
  policy_id text NOT NULL CHECK(policy_id='LAB-NEUTRAL-NO-HERO-RESOLUTION-V1'),
  source_ref text NOT NULL CHECK(length(source_ref) BETWEEN 3 AND 255),
  profile_source_ref text NOT NULL CHECK(length(profile_source_ref) BETWEEN 3 AND 255),
  original_count integer NOT NULL CHECK(original_count BETWEEN 1 AND 1000000),
  neutral_deaths integer NOT NULL CHECK(neutral_deaths=original_count),
  recorded_at timestamptz NOT NULL DEFAULT clock_timestamp()
);

CREATE FUNCTION prevent_pve_neutral_ledger_mutation_v103() RETURNS trigger
LANGUAGE plpgsql AS $ledger$
BEGIN
  IF TG_OP='UPDATE' OR EXISTS (
    SELECT 1 FROM pve_missions WHERE mission_id=OLD.mission_id
  ) THEN
    RAISE EXCEPTION 'Neutral resolution ledger is append-only'
      USING ERRCODE='23514';
  END IF;
  RETURN OLD;
END;
$ledger$;
CREATE TRIGGER pve_neutral_ledger_append_only_v103
BEFORE UPDATE OR DELETE ON pve_lab_neutral_resolutions FOR EACH ROW
EXECUTE FUNCTION prevent_pve_neutral_ledger_mutation_v103();

CREATE FUNCTION prevent_resurrection_of_resolved_neutral_v103() RETURNS trigger
LANGUAGE plpgsql AS $resolved$
BEGIN
  IF OLD.resolved AND (
      NOT NEW.resolved OR
      ROW(NEW.encounter_id,NEW.city_id,NEW.cell_i,NEW.cell_j,
          NEW.unit_code,NEW.unit_count,NEW.unit_power,NEW.source_ref)
      IS DISTINCT FROM
      ROW(OLD.encounter_id,OLD.city_id,OLD.cell_i,OLD.cell_j,
          OLD.unit_code,OLD.unit_count,OLD.unit_power,OLD.source_ref)
  ) THEN
    RAISE EXCEPTION 'Resolved neutral encounter is historically immutable'
      USING ERRCODE='23514';
  END IF;
  RETURN NEW;
END;
$resolved$;
CREATE TRIGGER pve_neutral_resolved_immutable_v103
BEFORE UPDATE ON region_encounters FOR EACH ROW
EXECUTE FUNCTION prevent_resurrection_of_resolved_neutral_v103();

COMMENT ON COLUMN pve_missions.neutral_resolution_snapshot IS
  'V103 opt-in neutral no-hero/no-attrition qualification at dispatch; NULL historical mission.';
COMMENT ON TABLE pve_lab_neutral_resolutions IS
  'Opt-in LAB neutral encounter clearance only. No mine production, XP, loot or player territory.';

#!/usr/bin/env python3
"""Run MMHK browser/security regression in a disposable LOCAL Docker project.

This command NEVER uses .env.local, the persistent mmhk-local project or its
PostgreSQL volume. It creates a unique qa project, disposable credentials,
and an isolated host port, runs genuine browsers against real FastAPI, then
destroys only its own Docker project unless --keep is explicitly requested.

No existing password, login, city or project is required.
"""
from __future__ import annotations

import argparse
import os
from pathlib import Path
import re
import secrets
import shutil
import socket
import subprocess
import sys
import venv

ROOT=Path(__file__).resolve().parents[2]
WORK=ROOT/".qa-local"
REPORTS=WORK/"reports"
PLAYWRIGHT_VERSION="1.56.0"
DEMO_USER="demo_ci"

def available(command,description):
    if not shutil.which(command):
        raise RuntimeError(description+" introuvable. Consultez docs/TESTS-LOCAUX.md.")

def prerequisites():
    if sys.version_info < (3,10):
        raise RuntimeError("Python >=3.10 requis")
    available("docker","Docker Desktop / Docker Engine")
    for args,label in (
        (["docker","compose","version"],"Docker Compose v2"),
        (["docker","info","--format","{{.ServerVersion}}"],"Docker actif")
    ):
        p=subprocess.run(args,cwd=ROOT,text=True,capture_output=True,check=False)
        if p.returncode:
            raise RuntimeError(label+" indisponible. Demarrez Docker Desktop.")

def free_port():
    with socket.socket() as s:
        s.bind(("127.0.0.1",0))
        return s.getsockname()[1]

def venv_python():
    path=WORK/"venv"
    python=path/("Scripts/python.exe" if os.name=="nt" else "bin/python")
    if not python.is_file():
        venv.EnvBuilder(with_pip=True).create(path)
    # A half-installed virtualenv can already contain python.exe but no
    # Playwright. Always verify the pinned module, repairing it when needed.
    probe=subprocess.run(
        [str(python),"-c",
         "import importlib.metadata as m; assert m.version('playwright')=='"+
         PLAYWRIGHT_VERSION+"'"],
        cwd=ROOT,capture_output=True,check=False
    )
    if probe.returncode:
        print("Installation locale isolee de Playwright...",flush=True)
        p=subprocess.run(
            [str(python),"-m","pip","install","--disable-pip-version-check",
             "--quiet","playwright=="+PLAYWRIGHT_VERSION],
            cwd=ROOT,check=False
        )
        if p.returncode:
            raise RuntimeError("Installation Playwright impossible dans .qa-local/venv")
    return python

def browser_dependencies(python,full):
    engines=["chromium","firefox","webkit"] if full else ["chromium"]
    print("Verification des navigateurs Playwright : "+", ".join(engines),flush=True)
    result=subprocess.run([str(python),"-m","playwright","install",*engines],
                          cwd=ROOT,check=False)
    if result.returncode:
        raise RuntimeError("Navigateurs indisponibles. Installez les dependances OS de Playwright.")

def run_hidden(args,*,env=None,stdin=None,timeout=450):
    """Hide one-time credentials generated by Docker before printing output."""
    p=subprocess.run(args,cwd=ROOT,input=stdin,text=True,
                     capture_output=True,check=False,timeout=timeout,env=env)
    if p.returncode:
        # No captured raw stdout/stderr is printed: seeding may emit secrets.
        raise RuntimeError("Commande Docker locale en echec (sortie protegee)")
    return p.stdout

def run_test(python,path,env,report,secret,timeout=480):
    print("\n[QA] "+path,flush=True)
    output=subprocess.run([str(python),"-u",str(ROOT/path)],
                          cwd=ROOT,env=env,capture_output=True,text=True,
                          check=False,timeout=timeout)
    safe=(output.stdout+"\n"+output.stderr).replace(secret,"[SECRET MASQUE]")
    (report/(Path(path).stem+".log")).write_text(safe,encoding="utf-8")
    for line in safe.splitlines():
        if line.startswith(("PASS","FAIL","Traceback","AssertionError","ERROR")):
            print("  "+line[:300],flush=True)
    if output.returncode:
        print(safe[-3500:],file=sys.stderr,flush=True)
        raise RuntimeError("Echec de "+path+" (rapport : "+str(report)+")")

def docker(compose,*args,stdin=None,timeout=540):
    return run_hidden([*compose,*args],stdin=stdin,timeout=timeout)

def runner(full,keep):
    prerequisites()
    WORK.mkdir(exist_ok=True)
    REPORTS.mkdir(parents=True,exist_ok=True)
    python=venv_python()
    browser_dependencies(python,full)
    project="mmhk-qa-"+secrets.token_hex(4)
    port=free_port()
    directory=WORK/project
    directory.mkdir(mode=0o700)
    report=REPORTS/project
    report.mkdir(mode=0o700)
    env_file=directory/"qa.env"
    env_file.write_text(
        "# Docker QA jetable : ne pas reutiliser les secrets de votre jeu.\n"
        +"MMHK_LOCAL_PORT="+str(port)+"\n"
        +"MMHK_LOCAL_POSTGRES_PASSWORD="+secrets.token_hex(32)+"\n"
        +"MMHK_LOGIN_RATE_KEY="+secrets.token_hex(32)+"\n",
        encoding="utf-8",
    )
    try:
        env_file.chmod(0o600)
    except OSError:
        pass
    compose=[
        "docker","compose","--project-name",project,
        "--env-file",str(env_file),"-f",str(ROOT/"compose.local.yaml")
    ]
    env=os.environ.copy()
    env.update({
        "MMHK_E2E_COMPOSE_PROJECT":project,
        "MMHK_E2E_ENV_FILE":str(env_file),
        "MMHK_E2E_URL":"http://127.0.0.1:"+str(port),
        "MMHK_E2E_USERNAME":DEMO_USER,
    })
    password=None
    ready=False
    print("\nBac QA isole : "+project+" (port "+str(port)+")",flush=True)
    print("Votre monde habituel mmhk-local / .env.local ne sera pas modifie.",flush=True)
    try:
        print("[QA] Construction et lancement de six services Docker...",flush=True)
        docker(compose,"up","-d","--build","--wait",timeout=1500)
        ready=True
        output=docker(compose,"run","--rm","-T","api","python",
                      "-m","mmhk_api.local_demo","--username",DEMO_USER,
                      timeout=180)
        found=re.search(r"^One-time generated password:\s*(\S+)",
                        output,re.M)
        if not found:
            raise RuntimeError("Le compte QA n'a pas fourni son mot de passe jetable")
        password=found.group(1)
        env["MMHK_E2E_PASSWORD"]=password
        docker(compose,"exec","-T","api","python","-m","mmhk_api.demo_expansion",
               timeout=90)
        basic=[
            "tools/e2e/player_visual_audit.py",
            "tools/e2e/responsive_visual_audit.py",
            "tools/e2e/dialog_accessibility_browser.py",
            "tools/e2e/dialog_busy_browser.py",
            "tools/e2e/login_access_browser.py",
        ]
        if full:
            basic.append("tools/e2e/cross_browser_access_browser.py")
        basic += [
            "tools/e2e/logout_offline_browser.py",
            "tools/e2e/session_lifecycle_browser.py",
            "tools/e2e/session_outage_browser.py",
            "tools/e2e/private_route_outage_browser.py",
            "tools/e2e/native_reverse_drag_browser.py",
        ]
        for test in basic:
            run_test(python,test,env,report,password)
        if full:
            run_test(python,"tools/e2e/local_browser.py",env,report,password,timeout=550)
            steps=[
                (("exec","-T","api","python","-m","mmhk_api.caravan_demo",
                  "--username",DEMO_USER,"--enable-second-city"),
                 "tools/e2e/caravans_browser.py"),
                (("exec","-T","api","python","-m","mmhk_api.colony_demo",
                  "--username",DEMO_USER,"--enable-colony-laboratory",
                  "--age-membership-for-test"),
                 "tools/e2e/colonization_browser.py"),
                (("exec","-T","api","python","-m","mmhk_api.influence_demo",
                  "--username",DEMO_USER,"--enable-influence-laboratory",
                  "--military-power","30000"),
                 "tools/e2e/influence_browser.py"),
            ]
            for command,test in steps:
                docker(compose,*command,timeout=150)
                run_test(python,test,env,report,password,timeout=480)
            manifest=ROOT/"data/fixtures/terrain-lab-profiles.json"
            if not manifest.is_file():
                raise RuntimeError("Manifest terrain experimental introuvable")
            # The importer reads a local fixture from STDIN, never a public URL.
            docker(compose,"exec","-T","api","python","-m",
                   "mmhk_api.terrain_import","--username",DEMO_USER,
                   "--enable-terrain-laboratory",stdin=manifest.read_text(encoding="utf-8"),
                   timeout=150)
            run_test(python,"tools/e2e/terrain_browser.py",env,report,password)
        run_test(python,"tools/e2e/two_player_isolation_browser.py",env,report,password)
        print("\nQA REUSSIE : tous les scenarios selectionnes ont passe.",flush=True)
        print("Rapports : "+str(report.relative_to(ROOT)),flush=True)
        print("Captures des navigateurs : test-output/visuals/ (gitignored)",flush=True)
        return 0
    finally:
        if keep and ready:
            print("\n--keep : bac QA conserve sur http://127.0.0.1:"+str(port),flush=True)
            print("Identifiant temporaire : "+DEMO_USER,flush=True)
            if password:
                print("Mot de passe temporaire A CONSERVER localement : "+password,flush=True)
            print("Pour supprimer CE bac QA :",flush=True)
            print("docker compose --project-name "+project+" --env-file "+
                  str(env_file)+" -f compose.local.yaml down -v --remove-orphans",flush=True)
        else:
            print("\nNettoyage de CE projet QA uniquement (aucune autre base)...",flush=True)
            subprocess.run([*compose,"down","-v","--remove-orphans"],cwd=ROOT,
                           stdout=subprocess.DEVNULL,stderr=subprocess.DEVNULL,
                           check=False,timeout=240)
            env_file.unlink(missing_ok=True)
            try:
                directory.rmdir()
            except OSError:
                pass

def main():
    p=argparse.ArgumentParser(description="Tests MMHK locaux avec Docker isole")
    p.add_argument("mode",nargs="?",choices=("quick","full"),default="quick",
                   help="quick : securite/UX, full : ajoute campagne metier longue")
    p.add_argument("--keep",action="store_true",
                   help="conserver explicitement le seul bac QA pour inspection")
    args=p.parse_args()
    return runner(args.mode=="full",args.keep)

if __name__=="__main__":
    try:
        raise SystemExit(main())
    except (RuntimeError,OSError,subprocess.TimeoutExpired) as exc:
        print("ERREUR QA : "+str(exc),file=sys.stderr)
        raise SystemExit(1)
